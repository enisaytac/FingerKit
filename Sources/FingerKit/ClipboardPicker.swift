/// Panonun o anki durumu: hangi raf ve kart seçili, arama, önizleme
@Observable
final class BoardState {
    var history = ClipboardHistory()
    var query = ""
    /// Seçili kart: raf sırası ve raftaki sıra
    var cursor = (shelf: 0, index: 0)
    var preview: ClipItem?
    /// Yazısı okunan görsel
    var reading: UUID?
    /// Kısa süre görünen bilgi ("Yazı kopyalandı")
    var flash: String? {
        didSet {
            guard flash != nil else { return }
            DispatchQueue.main.asyncAfter(deadline: .now() + 1.6) { [weak self] in self?.flash = nil }
        }
    }

    func items(_ shelf: ClipShelf) -> [ClipItem] { history.shelf(shelf, query: query) }

    var current: ClipItem? {
        let list = items(ClipShelf.allCases[cursor.shelf])
        return list.indices.contains(cursor.index) ? list[cursor.index] : nil
    }

    /// İlk dolu raf; yazılar önce (en sık yapıştırılan)
    func firstCursor() -> (shelf: Int, index: Int) {
        let order = [ClipShelf.texts, .captures, .images, .links].compactMap { ClipShelf.allCases.firstIndex(of: $0) }
        return (order.first { !items(ClipShelf.allCases[$0]).isEmpty } ?? order[0], 0)
    }

    func move(dx: Int = 0, dy: Int = 0) {
        if dy != 0 {
            // Boş raflar atlanır
            var s = cursor.shelf
            repeat { s += dy } while ClipShelf.allCases.indices.contains(s) && items(ClipShelf.allCases[s]).isEmpty
            guard ClipShelf.allCases.indices.contains(s) else { return }
            cursor = (s, min(cursor.index, max(items(ClipShelf.allCases[s]).count - 1, 0)))
        } else {
            let count = items(ClipShelf.allCases[cursor.shelf]).count
            cursor.index = min(max(cursor.index + dx, 0), max(count - 1, 0))
        }
    }

    func isSelected(_ shelf: ClipShelf, _ i: Int) -> Bool {
        ClipShelf.allCases[cursor.shelf] == shelf && cursor.index == i
    }
}

struct ClipboardBoard: View {
    let state: BoardState
    let pick: (ClipItem) -> Void
    let pin: (ClipItem) -> Void
    let readText: (ClipItem) -> Void

    var body: some View {
        ZStack {
            VStack(alignment: .leading, spacing: 0) {
                header
                if state.history.items.isEmpty {
                    Text(String(localized: "Henüz kopya yok. Bir yazıyı, görseli ya da bağlantıyı ⌘C ile kopyala; ekran görüntüleri de kendiliğinden gelir."))
                        .foregroundStyle(.secondary)
                        .multilineTextAlignment(.center)
                        .padding(40)
                        .frame(maxWidth: .infinity, maxHeight: .infinity)
                } else {
                    ScrollView(.vertical) {
                        VStack(alignment: .leading, spacing: UIStyle.pad(14)) {
                            ForEach(ClipShelf.allCases, id: \.self) { shelf in
                                ShelfRow(shelf: shelf, state: state, pick: pick, pin: pin, readText: readText)
                            }
                        }
                        .padding(.vertical, UIStyle.pad(8))
                    }
                }
                footer
            }
            if let item = state.preview {
                ClipPreview(item: item) { state.preview = nil }
                    .transition(.opacity)
            }
        }
        .background {
            let shape = RoundedRectangle.panel
            shape.fill(Color.nightBackground.opacity(0.97))
                .overlay(shape.fill(LinearGradient(colors: [.white.opacity(0.05), .clear], startPoint: .top, endPoint: .center)))
        }
        .clipShape(RoundedRectangle.panel)
        .environment(\.colorScheme, .dark)
        .tint(.fingerGold)
        .animation(.snappy(duration: 0.18), value: state.preview)
    }

    private var header: some View {
        HStack(spacing: 10) {
            Image(systemName: "magnifyingglass").foregroundStyle(.secondary)
            Text(state.query.isEmpty ? String(localized: "Yazarak ara") : state.query)
                .foregroundStyle(state.query.isEmpty ? .secondary : .primary)
                .lineLimit(1)
            Spacer()
            if let flash = state.flash {
                Label(flash, systemImage: "checkmark.circle.fill")
                    .foregroundStyle(Color.fingerGold)
                    .transition(.opacity)
            }
        }
        .font(.system(size: 15))
        .padding(.horizontal, 16)
        .frame(height: UIStyle.control + 8)
        .background(Capsule().fill(Color.white.opacity(0.07)))
        .padding(.horizontal, UIStyle.pad(14))
        .padding(.top, UIStyle.pad(14))
        .padding(.bottom, UIStyle.pad(4))
    }

    private var footer: some View {
        HStack(spacing: 18) {
            hint("←→↑↓", String(localized: "gez"))
            hint("↩", String(localized: "yapıştır"))
            hint(String(localized: "Boşluk"), String(localized: "önizle"))
            hint("P", String(localized: "sabitle"))
            hint("T", String(localized: "görseldeki yazıyı kopyala"))
            hint("Esc", String(localized: "kapat"))
            Spacer()
        }
        .font(.system(size: 11.5))
        .foregroundStyle(.secondary)
        .padding(.horizontal, UIStyle.pad(20))
        .padding(.vertical, UIStyle.pad(10))
        .background(Color.white.opacity(0.035))
    }

    private func hint(_ key: String, _ text: String) -> some View {
        HStack(spacing: 5) {
            Text(key)
                .font(.system(size: 11, weight: .semibold, design: .rounded))
                .padding(.horizontal, 7)
                .padding(.vertical, 2)
                .background(Capsule().fill(Color.white.opacity(0.1)))
            Text(text)
        }
    }
}

/// Bir raf: başlık ve yatay kayan kartlar
private struct ShelfRow: View {
    let shelf: ClipShelf
    let state: BoardState
    let pick: (ClipItem) -> Void
    let pin: (ClipItem) -> Void
    let readText: (ClipItem) -> Void

    var body: some View {
        let items = state.items(shelf)
        VStack(alignment: .leading, spacing: 8) {
            Label("\(shelf.title)  \(items.count)", systemImage: shelf.symbol)
                .font(.system(size: 12, weight: .semibold))
                .foregroundStyle(.secondary)
                .padding(.horizontal, 20)
            if items.isEmpty {
                Text(state.query.isEmpty ? String(localized: "Boş") : String(localized: "“\(state.query)” geçen yok"))
                    .font(.callout)
                    .foregroundStyle(.tertiary)
                    .padding(.horizontal, 20)
                    .frame(height: 40)
            } else {
                ScrollViewReader { proxy in
                    ScrollView(.horizontal, showsIndicators: false) {
                        LazyHStack(spacing: UIStyle.pad(10)) {
                            ForEach(Array(items.prefix(200).enumerated()), id: \.element.id) { i, item in
                                ClipCard(item: item, selected: state.isSelected(shelf, i), reading: state.reading == item.id)
                                    .id(item.id)
                                    .onTapGesture { pick(item) }
                                    .onHover { if $0 { state.cursor = (ClipShelf.allCases.firstIndex(of: shelf)!, i) } }
                                    .contextMenu {
                                        Button(String(localized: "Yapıştır")) { pick(item) }
                                        Button(item.pinned ? String(localized: "Sabitliği kaldır") : String(localized: "Sabitle")) { pin(item) }
                                        Button(String(localized: "Önizle")) { state.preview = item }
                                        if item.kind == .image {
                                            Button(String(localized: "Görseldeki yazıyı kopyala")) { readText(item) }
                                        }
                                        if let file = item.file {
                                            Button(String(localized: "Finder'da göster")) {
                                                NSWorkspace.shared.activateFileViewerSelecting([URL(fileURLWithPath: file)])
                                            }
                                        }
                                    }
                            }
                        }
                        .padding(.horizontal, UIStyle.pad(20))
                        // Kart gölgesi kesilmesin
                        .padding(.vertical, 8)
                    }
                    .frame(height: (shelf == .images || shelf == .captures ? 150 : 112) + 16)
                    .onChange(of: state.cursor.index) { _, i in
                        if state.isSelected(shelf, i), items.indices.contains(i) {
                            withAnimation(.snappy(duration: 0.2)) { proxy.scrollTo(items[i].id, anchor: .center) }
                        }
                    }
                }
            }
        }
    }
}

/// Kart: görselde küçük resim, yazıda ilk satırlar, bağlantıda alan adı ve adres
private struct ClipCard: View {
    let item: ClipItem
    let selected: Bool
    let reading: Bool

    var body: some View {
        VStack(alignment: .leading, spacing: 6) {
            content
            HStack(spacing: 4) {
                if item.pinned {
                    Image(systemName: "pin.fill").foregroundStyle(Color.fingerGold)
                }
                if item.kind == .video {
                    Image(systemName: "video.fill")
                }
                Text(caption)
                    .lineLimit(1)
                Spacer(minLength: 0)
                Text(item.age())
            }
            .font(.system(size: 10.5))
            .foregroundStyle(.secondary)
        }
        .padding(UIStyle.pad(8))
        .frame(width: width)
        .background {
            let shape = RoundedRectangle(cornerRadius: Self.radius, style: .continuous)
            shape.fill(Color.white.opacity(selected ? 0.13 : 0.06))
        }
        // Seçili kart: kenar çizgisi yerine sarı halka ve hafif ışık
        .overlay {
            if selected {
                RoundedRectangle(cornerRadius: Self.radius, style: .continuous)
                    .strokeBorder(Color.fingerGold, lineWidth: 2)
                    .shadow(color: Color.fingerGold.opacity(0.35), radius: 6)
            }
        }
        .overlay {
            if reading { ProgressView().controlSize(.small) }
        }
        .contentShape(Rectangle())
    }

    static var radius: CGFloat { (UIStyle.card * 0.7).rounded() }

    private var width: CGFloat {
        switch item.shelf {
        case .images, .captures: 170
        case .texts: 220
        case .links: 230
        }
    }

    private var caption: String {
        switch item.kind {
        case .text: String(localized: "\(item.text.count) harf")
        case .link: String(localized: "Bağlantı")
        case .image, .video: item.file.map { URL(fileURLWithPath: $0).deletingPathExtension().lastPathComponent } ?? ""
        }
    }

    @ViewBuilder
    private var content: some View {
        switch item.kind {
        case .text:
            Text(item.text.trimmingCharacters(in: .whitespacesAndNewlines))
                .font(.system(size: 12.5))
                .lineLimit(4)
                .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
                .frame(height: 70)
        case .link:
            VStack(alignment: .leading, spacing: 4) {
                Label(item.host ?? "", systemImage: "globe")
                    .font(.system(size: 13, weight: .semibold))
                    .lineLimit(1)
                Text(item.text)
                    .font(.system(size: 11))
                    .foregroundStyle(.secondary)
                    .lineLimit(2)
                    .truncationMode(.middle)
            }
            .frame(maxWidth: .infinity, alignment: .topLeading)
            .frame(height: 70, alignment: .top)
        case .image, .video:
            Thumbnail(file: item.file)
                .frame(height: 108)
                .frame(maxWidth: .infinity)
                .clipShape(RoundedRectangle(cornerRadius: max(Self.radius - 6, 4), style: .continuous))
        }
    }
}

/// Dosyanın küçük resmi (Mac'in Quick Look küçük resmi; video da olur), önbellekli
private struct Thumbnail: View {
    let file: String?
    @State private var image: NSImage?

    var body: some View {
        ZStack {
            Color.white.opacity(0.04)
            if let image {
                Image(nsImage: image).resizable().aspectRatio(contentMode: .fit)
            } else {
                Image(systemName: "photo").foregroundStyle(.tertiary)
            }
        }
        .task(id: file) { image = await ThumbnailCache.image(for: file) }
    }
}

@MainActor
enum ThumbnailCache {
    nonisolated(unsafe) private static let cache = NSCache<NSString, NSImage>()

    static func image(for file: String?) async -> NSImage? {
        guard let file else { return nil }
        if let hit = cache.object(forKey: file as NSString) { return hit }
        let request = QLThumbnailGenerator.Request(fileAt: URL(fileURLWithPath: file), size: CGSize(width: 340, height: 220),
                                                   scale: 2, representationTypes: .thumbnail)
        guard let rep = try? await QLThumbnailGenerator.shared.generateBestRepresentation(for: request) else { return nil }
        cache.setObject(rep.nsImage, forKey: file as NSString)
        return rep.nsImage
    }
}

/// Boşluk: kartın büyük hâli (görsel, video oynar, yazının tamamı, bağlantı)
private struct ClipPreview: View {
    let item: ClipItem
    let close: () -> Void

    var body: some View {
        ZStack {
            Color.black.opacity(0.75)
                .onTapGesture(perform: close)
            VStack(spacing: 12) {
                switch item.kind {
                case .image:
                    if let file = item.file, let image = NSImage(contentsOfFile: file) {
                        Image(nsImage: image).resizable().aspectRatio(contentMode: .fit)
                    }
                case .video:
                    if let file = item.file {
                        VideoPlayer(player: AVPlayer(url: URL(fileURLWithPath: file)))
                    }
                case .text, .link:
                    ScrollView {
                        Text(item.text)
                            .font(.system(size: 14))
                            .textSelection(.enabled)
                            .frame(maxWidth: .infinity, alignment: .leading)
                            .padding(16)
                    }
                    .background(RoundedRectangle.card.fill(Color.white.opacity(0.06)))
                }
                Text(String(localized: "↩ yapıştır · Boşluk ya da Esc kapat"))
                    .font(.caption)
                    .foregroundStyle(.secondary)
            }
            .padding(30)
        }
    }
}
