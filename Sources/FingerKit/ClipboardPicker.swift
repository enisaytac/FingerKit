/// Panoya saniyede iki kez bakar; yeni bir şey kopyalandıysa geçmişe ekler (yazı, bağlantı, görsel).
/// macOS'ta "kopyalandı" haberi yok; bütün pano uygulamaları böyle yapar.
final class ClipboardWatcher {
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private let folder: URL
    private let onCopy: (ClipItem) -> Void
    /// FingerKit'in kendi panoya koyduğu (yapıştırmak için) değişiklik; geçmişe yeniden eklenmez
    var ownChange = -1

    init(folder: URL, onCopy: @escaping (ClipItem) -> Void) {
        self.folder = folder
        self.onCopy = onCopy
    }

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        // Açılmadan önce panoda duran şey eklenmez (her açılışta en üste çıkmasın)
        lastChange = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
        Log.write("Pano geçmişi açık")
    }

    func stop() {
        guard timer != nil else { return }
        timer?.invalidate()
        timer = nil
        Log.write("Pano geçmişi kapalı")
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard lastChange != ownChange else { return }
        // Şifre yöneticileri ve geçici kopyalar kendini işaretler (nspasteboard.org); bunlar saklanmaz
        let types = pasteboard.types ?? []
        if types.contains(where: Self.private.contains) { return }
        // Finder'da kopyalanan görsel ya da video dosyası: yerinde kalır, listede görünür
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           let url = urls.first, let kind = Self.mediaKind(url) {
            onCopy(ClipItem(kind: kind, text: url.deletingPathExtension().lastPathComponent, date: Date(), file: url.path))
            return
        }
        // Görsel (yazıyla birlikte gelmediyse; web'den kopyalanan yazı da bazen resim taşır)
        if pasteboard.string(forType: .string) == nil, let image = NSImage(pasteboard: pasteboard),
           let png = image.pngData() {
            let hash = SHA256.hash(data: png).prefix(12).map { String(format: "%02x", $0) }.joined()
            let file = folder.appendingPathComponent("\(hash).png")
            do {
                try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
                if !FileManager.default.fileExists(atPath: file.path) { try png.write(to: file) }
                onCopy(ClipItem(kind: .image, text: String(localized: "Görsel"), date: Date(), file: file.path, hash: hash))
            } catch {
                Log.write("HATA: görsel kaydedilemedi: \(error.localizedDescription)")
            }
            return
        }
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            onCopy(ClipItem(text: text, date: Date()))
        }
    }

    static func mediaKind(_ url: URL) -> ClipKind? {
        switch url.pathExtension.lowercased() {
        case "png", "jpg", "jpeg", "heic", "gif", "tiff", "webp": .image
        case "mov", "mp4", "m4v": .video
        default: nil
        }
    }

    private static let `private`: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
}

/// Ekran görüntüleri ve ekran kayıtları: Mac'in kaydettiği klasöre (varsayılan Masaüstü) 2 sn'de bir bakar,
/// yeni dosya listeye düşer. Dosya yerinde kalır; FingerKit kopyalamaz.
final class ScreenshotWatcher {
    private var timer: Timer?
    private var seen: Set<String> = []
    private let onShot: (ClipItem) -> Void

    init(onShot: @escaping (ClipItem) -> Void) {
        self.onShot = onShot
    }

    /// Mac'in ekran görüntüsü klasörü (Ekran Görüntüsü uygulamasının "Seçenekler › Kaydet" yeri)
    static var folder: URL {
        let saved = CFPreferencesCopyAppValue("location" as CFString, "com.apple.screencapture" as CFString) as? String
        if let saved, !saved.isEmpty {
            return URL(fileURLWithPath: (saved as NSString).expandingTildeInPath, isDirectory: true)
        }
        return FileManager.default.urls(for: .desktopDirectory, in: .userDomainMask)[0]
    }

    func start() {
        guard timer == nil else { return }
        // Açılıştaki dosyalar yeni sayılmaz
        seen = Set(files())
        timer = Timer.scheduledTimer(withTimeInterval: 2, repeats: true) { [weak self] _ in self?.check() }
        Log.write("Ekran görüntüsü klasörü izleniyor: \(Self.folder.path)")
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func files() -> [String] {
        let names = (try? FileManager.default.contentsOfDirectory(atPath: Self.folder.path)) ?? []
        return names.filter(ClipboardSettings.isScreenshot(fileName:))
    }

    private func check() {
        for name in files() where !seen.contains(name) {
            seen.insert(name)
            let url = Self.folder.appendingPathComponent(name)
            guard let kind = ClipboardWatcher.mediaKind(url) else { continue }
            onShot(ClipItem(kind: kind, text: url.deletingPathExtension().lastPathComponent, date: Date(), file: url.path))
        }
    }
}

extension NSImage {
    func pngData() -> Data? {
        guard let tiff = tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}

