/// Caps Lock + V: ekranın ortasında büyük pano. Üç raf: görseller (ekran görüntüleri ve kayıtları da), yazılar,
/// bağlantılar. Oklar gezer, ↩ yapıştırır, Boşluk önizler, P sabitler, T görseldeki yazıyı kopyalar,
/// yazınca aranır. Pencere odak çalmaz; öndeki uygulama öndeki kalır, seçilen şey ona yapıştırılır.
final class ClipboardPicker: NSObject, NSWindowDelegate {
    static let shared = ClipboardPicker()

    private var panel: PickerPanel?
    private var monitor: Any?
    private let state = BoardState()
    private weak var engine: Engine?

    var isShown: Bool { panel?.isVisible == true }

    func show(_ engine: Engine) {
        if isShown { close(); return }
        let started = CACurrentMediaTime()
        self.engine = engine
        state.query = ""
        state.preview = nil
        state.history = engine.clipHistory
        state.cursor = state.firstCursor()
        let panel = self.panel ?? makePanel()
        self.panel = panel
        panel.setFrame(frame(), display: true)
        panel.alphaValue = 0
        panel.makeKeyAndOrderFront(nil)
        NSAnimationContext.runAnimationGroup { $0.duration = 0.14; panel.animator().alphaValue = 1 }
        monitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] event in
            self?.key(event) == true ? nil : event
        }
        let count = engine.clipHistory.items.count
        // Bir sonraki turda ilk çizim bitmiş olur: açılışın süresi günlüğe yazılır
        DispatchQueue.main.async {
            Log.write(String(format: "Pano açıldı (%d kayıt, %.0f ms)", count, (CACurrentMediaTime() - started) * 1000))
        }
    }

    /// Açılıştan kısa süre sonra arkada bir kez kurulur: ilk ⇪ + V'de pencere beklemeden gelsin
    /// (soğuk kurulum ~360 ms donduruyordu)
    func warmUp(_ engine: Engine) {
        guard panel == nil else { return }
        state.history = engine.clipHistory
        state.cursor = state.firstCursor()
        let panel = makePanel()
        self.panel = panel
        panel.setFrame(frame(), display: false)
        // Görünmez olarak bir kez ekrana konur: ilk çizim (yazı tipleri, katmanlar) burada biter
        // (tıklamaları da geçirir, altındaki pencereye gider)
        panel.alphaValue = 0
        panel.ignoresMouseEvents = true
        panel.orderFrontRegardless()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.4) { [weak self] in
            panel.ignoresMouseEvents = false
            guard let self, self.monitor == nil else { return }
            panel.orderOut(nil)
        }
    }

    func close() {
        if let monitor { NSEvent.removeMonitor(monitor) }
        monitor = nil
        panel?.orderOut(nil)
    }

    func windowDidResignKey(_ notification: Notification) {
        close()
    }

    private func makePanel() -> PickerPanel {
        let panel = PickerPanel(contentRect: .zero, styleMask: [.nonactivatingPanel, .borderless], backing: .buffered, defer: false)
        panel.level = .popUpMenu
        panel.isFloatingPanel = true
        panel.hidesOnDeactivate = false
        panel.backgroundColor = .clear
        panel.isOpaque = false
        panel.hasShadow = true
        panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
        panel.delegate = self
        // Görünüm bir kez kurulur; her açılışta yalnız `state` değişir (baştan kurmak ~90 ms donduruyordu)
        let view = ClipboardBoard(state: state,
                                  pick: { [weak self] item in self?.pick(item) },
                                  pin: { [weak self] item in self?.togglePin(item) },
                                  readText: { [weak self] item in self?.readText(item) })
        panel.contentView = FirstClickHostingView(rootView: view)
        return panel
    }

    /// İmlecin olduğu ekranın ortası; ekranın çoğunu kaplamaz
    private func frame() -> NSRect {
        let mouse = NSEvent.mouseLocation
        let screen = NSScreen.screens.first { NSMouseInRect(mouse, $0.frame, false) } ?? NSScreen.main
        let v = screen?.visibleFrame ?? NSRect(x: 0, y: 0, width: 1440, height: 900)
        let w = min(v.width - 80, 1040), h = min(v.height - 80, 760)
        return NSRect(x: v.midX - w / 2, y: v.midY - h / 2, width: w, height: h)
    }

    /// true: tuş panoda kullanıldı (yutulur)
    private func key(_ event: NSEvent) -> Bool {
        if state.preview != nil {
            // Önizleme açıkken: Boşluk ya da Esc kapatır, ↩ yapıştırır
            switch event.keyCode {
            case 49, 53: state.preview = nil
            case 36, 76: if let item = state.preview { pick(item) }
            default: break
            }
            return true
        }
        let commandish = !event.modifierFlags.intersection([.command, .control]).isEmpty
        switch event.keyCode {
        case 53: close()
        case 36, 76: if let item = state.current { pick(item) }
        case 123: state.move(dx: -1)
        case 124: state.move(dx: 1)
        case 125: state.move(dy: 1)
        case 126: state.move(dy: -1)
        case 49 where state.query.isEmpty: state.preview = state.current
        case 51:
            if !state.query.isEmpty { state.query.removeLast(); state.cursor = state.firstCursor() }
        default:
            if commandish { return false }
            guard let chars = event.characters, !chars.isEmpty,
                  chars.unicodeScalars.allSatisfy({ !CharacterSet.controlCharacters.contains($0) }) else { return true }
            // Arama boşken tek harfli komutlar: P sabitle, T görseldeki yazıyı kopyala
            if state.query.isEmpty, let item = state.current {
                switch chars.lowercased() {
                case "p": togglePin(item); return true
                case "t" where item.kind == .image: readText(item); return true
                default: break
                }
            }
            state.query += chars
            state.cursor = state.firstCursor()
        }
        return true
    }

    private func togglePin(_ item: ClipItem) {
        engine?.clipHistory.togglePin(item.id)
        if let engine { state.history = engine.clipHistory }
    }

    /// Görseldeki yazıyı Mac'in kendi yazı tanıma özelliğiyle okur (internete gitmez), panoya koyar
    private func readText(_ item: ClipItem) {
        guard let file = item.file else { return }
        state.reading = item.id
        TextReader.read(URL(fileURLWithPath: file)) { [weak self] text in
            guard let self else { return }
            state.reading = nil
            guard let text, !text.isEmpty else {
                state.flash = String(localized: "Görselde yazı bulunamadı")
                return
            }
            engine?.clipHistory.setText(text, for: item.id)
            if let engine { state.history = engine.clipHistory }
            let pasteboard = NSPasteboard.general
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
            state.flash = String(localized: "Yazı kopyalandı (\(text.count) harf)")
            Log.write("Pano: görseldeki yazı okundu (\(text.count) harf)")
        }
    }

    private func pick(_ item: ClipItem) {
        close()
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link:
            pasteboard.setString(item.text, forType: .string)
        case .image:
            guard let file = item.file else { return }
            let url = URL(fileURLWithPath: file)
            // Görsel olarak (Notlar, Mesajlar, Pages) ve dosya olarak (Finder) yapıştırılabilsin
            var objects: [NSPasteboardWriting] = []
            if let image = NSImage(contentsOf: url) { objects.append(image) }
            objects.append(url as NSURL)
            pasteboard.writeObjects(objects)
        case .video:
            guard let file = item.file else { return }
            pasteboard.writeObjects([URL(fileURLWithPath: file) as NSURL])
        }
        engine?.markOwnPaste()
        Log.write("Pano: yapıştırıldı (\(item.kind.rawValue))")
        // Pano kapanıp öndeki uygulama tuşları yeniden alsın diye kısa bekleme
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.06) { KeySender.paste() }
    }
}

/// Görseldeki yazıyı okur (Vision; Türkçe ve İngilizce, cihazda)
enum TextReader {
    static func read(_ url: URL, done: @escaping (String?) -> Void) {
        DispatchQueue.global(qos: .userInitiated).async {
            let request = VNRecognizeTextRequest()
            request.recognitionLevel = .accurate
            request.usesLanguageCorrection = true
            request.recognitionLanguages = ["tr-TR", "en-US"]
            let handler = VNImageRequestHandler(url: url)
            try? handler.perform([request])
            let lines = (request.results ?? []).compactMap { $0.topCandidates(1).first?.string }
            DispatchQueue.main.async { done(lines.isEmpty ? nil : lines.joined(separator: "\n")) }
        }
    }
}

